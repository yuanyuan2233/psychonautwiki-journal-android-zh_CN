    /**
     * 快捷获取中文名称
     */
    fun getLocalizedName(name: String): String = getSubstanceDisplayName(name)

    fun isChinese(): Boolean {
        return Locale.getDefault().language.startsWith("zh")
    }

    /**
     * 获取物质的主要展示名称（中文环境优先返回中文标准名，英文环境优先返回英文名）
     */
    fun getSubstanceDisplayName(name: String, commonNames: List<String> = emptyList()): String {
        val trimmed = name.trim()
        if (trimmed.isEmpty()) return ""

        if (!isChinese()) {
            if (!containsChinese(trimmed)) {
                return trimmed
            }
            val parenIndex = trimmed.indexOfAny(charArrayOf('(', '（'))
            if (parenIndex > 0) {
                val prefix = trimmed.substring(0, parenIndex).trim()
                if (!containsChinese(prefix)) {
                    return prefix
                }
            }
            val enName = ZH_NAME_MAP.entries.firstOrNull { it.value.equals(trimmed, ignoreCase = true) }?.key
            if (enName != null) return enName
            val enInCommon = commonNames.firstOrNull { !containsChinese(it) && !isPinyinToken(it) }
            if (enInCommon != null) return enInCommon.trim()
            return trimmed
        }
        
        // 1. 查静态字典
        ZH_NAME_MAP[trimmed]?.let { return it }
        val foundIgnoreCase = ZH_NAME_MAP.entries.firstOrNull { it.key.equals(trimmed, ignoreCase = true) }?.value
        if (foundIgnoreCase != null) return foundIgnoreCase

        // 1.1 尝试去除末尾复数 's' 再次匹配
        if (trimmed.endsWith("s", ignoreCase = true) && trimmed.length > 2) {
            val singular = trimmed.substring(0, trimmed.length - 1)
            val foundSingular = ZH_NAME_MAP.entries.firstOrNull { it.key.equals(singular, ignoreCase = true) }?.value
            if (foundSingular != null) return foundSingular
        }

        // 1.2 如果包含 '|'，尝试拆分翻译后用 '/' 拼接
        if (trimmed.contains('|')) {
            val parts = trimmed.split('|').map { it.trim() }
            val translatedParts = parts.map { part ->
                ZH_NAME_MAP.entries.firstOrNull { it.key.equals(part, ignoreCase = true) }?.value ?: part
            }
            if (translatedParts.any { containsChinese(it) }) {
                return translatedParts.distinct().joinToString("/")
            }
        }

        // 1.3 尝试解析 "英文词 (中文说明)" 的混合格式，精准替换前缀英文
        val parenIndex = trimmed.indexOfAny(charArrayOf('(', '（'))
        if (parenIndex > 0) {
            val prefix = trimmed.substring(0, parenIndex).trim()
            val suffix = trimmed.substring(parenIndex).trim()
            val translatedPrefix = ZH_NAME_MAP[prefix]
                ?: ZH_NAME_MAP.entries.firstOrNull { it.key.equals(prefix, ignoreCase = true) }?.value
                ?: if (prefix.endsWith("s", ignoreCase = true) && prefix.length > 2) {
                    val sing = prefix.substring(0, prefix.length - 1)
                    ZH_NAME_MAP.entries.firstOrNull { it.key.equals(sing, ignoreCase = true) }?.value
                } else null
            if (translatedPrefix != null) {
                return "$translatedPrefix $suffix"
            }
        }

        // 2. 本身包含中文汉字，直接返回
        if (containsChinese(trimmed)) return trimmed

        // 3. 从 commonNames 提取首个包含中文的项
        val zhInCommon = commonNames.firstOrNull { containsChinese(it) }
        if (zhInCommon != null) return zhInCommon.trim()

        // 4. 回退原名
        return trimmed
    }

    /**
     * 获取副标题 / 小字文本（包含原英文名与别名，排重，过滤检索专用拼音）
     */
    fun getSubstanceSecondaryText(
        name: String,
        commonNames: List<String>,
        displayName: String
    ): String {
        val list = mutableListOf<String>()
        val trimmedName = name.trim()
        if (isChinese()) {
            // 如果显示名称是中文，且原名与显示名称不同，优先把英文原名放在副标首位
            if (trimmedName.isNotEmpty() && !trimmedName.equals(displayName, ignoreCase = true)) {
                list.add(trimmedName)
            }
        }
        // 加入其他人类可读别名（排除 displayName 与内部拼音标记）
        for (item in commonNames) {
            val trimmed = item.trim()
            if (trimmed.isEmpty() || trimmed.equals(displayName, ignoreCase = true)) continue
            if (isPinyinToken(trimmed)) continue
            if (!isChinese() && containsChinese(trimmed)) continue
            if (!list.contains(trimmed)) {
                list.add(trimmed)
            }
            if (list.size >= 5) break
        }
        return list.joinToString(", ")
    }

    private fun isPinyinToken(str: String): Boolean {
        // 如果包含中文，是合法汉字别名，不过滤
        if (containsChinese(str)) return false
        // 带单引号的隔音符拼音（如 pu'rui'ba'lin），过滤
        if (str.contains('\'')) return true
        // 全大写或含数字的化学缩写代号（如 LSD, DXM, 2C-B, PCP, MDMA），保留
        if (str.all { it.isUpperCase() || it.isDigit() || it == '-' || it == '+' || it == ' ' }) return false
        // 首字母大写的专有名词（如 Lyrica, Xanax），保留
        if (str.isNotEmpty() && str[0].isUpperCase() && !str.contains('(')) return false
        // 全小写字母且长度>=3（如 prbl, puruibalin, lrk），属于检索拼音标记，过滤
        if (str.length >= 2 && str.all { it.isLowerCase() }) return true
        // 含有括号杂项的拼音标记
        if (str.contains('(') || str.contains(')')) return true
        return false
    }

    private fun containsChinese(str: String): Boolean {
        for (ch in str) {
            if (ch in '\u4e00'..'\u9fa5') return true
        }
        return false
    }
